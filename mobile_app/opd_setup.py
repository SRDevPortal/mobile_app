"""Install and migrate partitioned OPD state, indexed visits and audit records."""
import frappe
from mobile_app import opd_store as store

LEGACY = {'OPD Clinic':'Clinic','OPD Room':'Room','OPD Department Route':'Route',
    'OPD Room Session':'Session','OPD Visit':'Visit','OPD Queue Event':'Event'}


def after_migrate():
    from frappe.custom.doctype.custom_field.custom_field import create_custom_fields
    create_custom_fields({'Healthcare Settings':[{'fieldname':store.FIELD,
        'label':'Doctor Clinical room configuration','fieldtype':'Long Text','hidden':1,'read_only':1}]},update=True)
    for role in ('OPD Staff','OPD Display'):
        if not frappe.db.exists('Role',role):
            frappe.get_doc({'doctype':'Role','role_name':role,'desk_access':1}).insert(ignore_permissions=True)
    for fields in (['opd_clinic','opd_status'],['opd_patient']):frappe.db.add_index(store.WORKFLOW,fields)
    if not frappe.db.sql('SELECT value FROM `tabSingles` WHERE doctype=%s AND field=%s',(store.SETTINGS,store.FIELD)):
        frappe.db.set_single_value(store.SETTINGS,store.FIELD,frappe.as_json({k:{} for k in store.COLLECTIONS.values()}))
    setup_partitioned_storage()
    previous=frappe.flags.in_opd_mutation;frappe.flags.in_opd_mutation=True
    try:
        store.lock()
        # Preserve any state from the earlier local implementation before removing its DocTypes.
        for doctype,kind in LEGACY.items():
            if not frappe.db.exists('DocType',doctype):continue
            for name in frappe.get_all(doctype,pluck='name'):
                old=frappe.db.get_value(doctype,name,'*',as_dict=True)
                for field in frappe.get_meta(doctype).fields:
                    if field.fieldtype=='Table':
                        old[field.fieldname]=frappe.db.get_values(field.options,{'parent':name,'parenttype':doctype,'parentfield':field.fieldname},'*',as_dict=True,order_by='idx')
                if kind=='Event' and store.event_for_request(old.request_key):continue
                if kind!='Event' and store.value(kind,name):continue
                store.save(store.Record(kind,old))
        if not store.all('Clinic'):
            store.save(store.Record('Clinic',{'name':'main-clinic','clinic_name':'Main Clinic','enabled':1}))
        config=store.configuration()
        if not config.get('default_clinic'):
            primary=next(iter(config['clinics'].values()))
            if primary.get('clinic_name')=='Main Clinic':primary['clinic_name']='Gurgaon'
            primary.setdefault('code','GGN');primary.setdefault('timezone',frappe.utils.get_system_timezone())
            config['default_clinic']=primary['name'];store.write_configuration(config)
        # Remove only the superseded OPD metadata. Frappe retains old SQL tables as migration backups.
        for doctype in ['OPD Queue Event','OPD Visit','OPD Room Session','OPD Department Route','OPD Room','OPD Clinic',
                        'OPD Visit Stage','OPD Room Assignment','OPD Display User']:
            if frappe.db.exists('DocType',doctype):
                frappe.delete_doc('DocType',doctype,force=True,ignore_permissions=True,ignore_on_trash=True)
        if frappe.db.exists("Page","opd-queue"):
            frappe.delete_doc("Page","opd-queue",force=True,ignore_permissions=True)
    finally:frappe.flags.in_opd_mutation=previous


def setup_partitioned_storage():
    """One-time transactional data move; retained records keep their public IDs."""
    import json
    frappe.reload_doc('mobileapp', 'doctype', 'opd_state_record')
    frappe.reload_doc('mobileapp', 'doctype', 'mobile_appointment_workflow')
    frappe.db.add_index(store.STATE, ['record_type', 'clinic'], 'opd_state_type_clinic')
    frappe.db.add_index(store.WORKFLOW, ['opd_clinic', 'opd_visit_date'], 'opd_clinic_visit_date')
    frappe.db.add_index(store.WORKFLOW, ['opd_clinic', 'opd_status', 'opd_visit_date'], 'opd_clinic_status_date')
    rows = frappe.db.sql('SELECT value FROM `tabSingles` WHERE doctype=%s AND field=%s FOR UPDATE', (store.SETTINGS, store.FIELD))
    if not rows: return
    config = json.loads(rows[0][0] or '{}')
    if config.get('storage_version') == 2: return
    for kind, collection in store.COLLECTIONS.items():
        for name, data in config.get(collection, {}).items():
            store._save_state(kind, name, name if kind == 'Clinic' else data['clinic'], data)
    for name, clinic in config.get('appointment_branches', {}).items():
        store._save_state('AppointmentBranch', name, clinic, {})
    # Date values were generated by getdate(); JSON_VALID protects legacy malformed payloads.
    frappe.db.sql("""UPDATE `tabMobile Appointment Workflow`
        SET opd_visit_date=STR_TO_DATE(JSON_UNQUOTE(JSON_EXTRACT(opd_payload, '$.visit_date')), '%Y-%m-%d')
        WHERE opd_payload IS NOT NULL AND opd_payload != '' AND JSON_VALID(opd_payload)
          AND opd_visit_date IS NULL""")
    frappe.db.sql("""UPDATE `tabMobile Appointment Workflow`
        SET opd_queue_status=CASE WHEN opd_status='Active' THEN
          JSON_UNQUOTE(JSON_EXTRACT(opd_payload, CONCAT('$.stages[',
            JSON_UNQUOTE(JSON_EXTRACT(opd_payload, '$.stage_index')), '].state')))
          ELSE opd_status END
        WHERE opd_payload IS NOT NULL AND opd_payload != '' AND JSON_VALID(opd_payload)""")
    if frappe.db.count(store.WORKFLOW, {'opd_payload':['is','set'], 'opd_visit_date':['is','not set']}):
        frappe.throw('OPD migration found visit payloads without a valid date. Repair those records before retrying.')
    metadata = {k:v for k,v in config.items() if k not in {*store.COLLECTIONS.values(), 'appointment_branches'}}
    metadata['storage_version'] = 2
    frappe.db.sql('UPDATE `tabSingles` SET value=%s WHERE doctype=%s AND field=%s',
        (frappe.as_json(metadata), store.SETTINGS, store.FIELD))
